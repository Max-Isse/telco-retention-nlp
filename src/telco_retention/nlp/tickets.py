"""Servable ticket classifiers: TF-IDF + logistic regression for theme, sentiment and urgency (D-024).

The phase 6 winners use sentence embeddings, which need torch at serving time. The served models are TF-IDF
pipelines (no torch, small image); their out-of-time scores are measured here, next to the embeddings models', so the
cost of that choice is on record. After evaluation the served pipelines are refitted on all 1,000 labelled tweets.
"""

from __future__ import annotations

from typing import Any

import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, f1_score

from telco_retention.config import Config
from telco_retention.nlp.classify import label_names, macro_f1_ci, tfidf_lr
from telco_retention.nlp.data import clean_text

TARGETS = ["theme_code", "sentiment", "urgency"]


def fit_ticket_models(
    df: pd.DataFrame, cfg: Config, human: pd.DataFrame | None = None
) -> tuple[dict[str, Any], pd.DataFrame]:
    """`df`: labelled tweets with `clean`, `period` and the three labels. Returns the bundle and the scores."""
    n_boot = int(cfg.section("nlp").get("bootstrap", 1000))
    train, test = df[df.period == "train"], df[df.period == "test"]
    rows, models = [], {}
    for target in TARGETS:
        m = tfidf_lr(cfg.seed).fit(train["clean"], train[target])
        pred = m.predict(test["clean"])
        lo, hi = macro_f1_ci(test[target].to_numpy(), pred, n_boot, cfg.seed)
        row: dict[str, Any] = {
            "target": target,
            "test_rows": len(test),
            "macro_f1": f1_score(test[target], pred, average="macro"),
            "ci_low": lo,
            "ci_high": hi,
            "accuracy": accuracy_score(test[target], pred),
        }
        if human is not None:
            h = human.merge(test[["tweet_id", "clean"]], on="tweet_id")
            hp = m.predict(h["clean"])
            row["macro_f1_vs_hand_labels"] = f1_score(h[target], hp, average="macro")
            row["hand_labelled_rows"] = len(h)
        rows.append(row)
        models[target] = tfidf_lr(cfg.seed).fit(df["clean"], df[target])  # served: refitted on all labels
    bundle = {
        "models": models,
        "theme_names": label_names(cfg),
        "trained_on": f"{len(df)} LLM-labelled tweets (D-020), TF-IDF + logistic regression",
        "scores": rows,
    }
    return bundle, pd.DataFrame(rows)


def classify_texts(texts: list[str], bundle: dict[str, Any]) -> list[dict[str, Any]]:
    cleaned = [clean_text(t) for t in texts]
    m = bundle["models"]
    theme_p = m["theme_code"].predict_proba(cleaned)
    urg_p = m["urgency"].predict_proba(cleaned)
    sent = m["sentiment"].predict(cleaned)
    theme_classes, urg_classes = m["theme_code"].classes_, list(m["urgency"].classes_)
    out = []
    for i, text in enumerate(cleaned):
        j = int(np.argmax(theme_p[i]))
        code = int(theme_classes[j])
        p_high = float(urg_p[i][urg_classes.index("high")])
        out.append(
            {
                "clean_text": text,
                "theme_code": code,
                "theme": bundle["theme_names"][code],
                "theme_probability": float(theme_p[i][j]),
                "sentiment": str(sent[i]),
                "urgency": "high" if p_high >= 0.5 else "normal",
                "p_urgent": p_high,
            }
        )
    return out


def write_ticket_report(scores: pd.DataFrame, cfg: Config) -> Any:
    tables = cfg.path("tables_dir")
    tables.mkdir(parents=True, exist_ok=True)
    scores.to_csv(tables / "ticket_serving_scores.csv", index=False)
    emb = []
    for name, target in [("theme", "theme_code"), ("sentiment", "sentiment"), ("urgency", "urgency")]:
        path = tables / f"nlp_{name}_scores.csv"
        if path.exists():
            s = pd.read_csv(path)
            hit = s[s.model.str.contains("embeddings")]
            if len(hit):
                emb.append({"target": target, "embeddings_macro_f1": float(hit.macro_f1.iloc[0])})
    comp = scores.merge(pd.DataFrame(emb), on="target", how="left") if emb else scores
    text = f"""<!-- GENERATED by `telco package-tickets` - do not edit by hand. -->
# Served ticket classifiers (D-024)

TF-IDF + logistic regression, trained on October, tested out of time on November onwards (LLM labels), and against
the hand labels of the test period where available. `embeddings_macro_f1` is the phase 6 embeddings model on the same
test set: the accuracy given up to serve without torch. The served pipelines are then refitted on all 1,000 labels.

{comp.to_markdown(index=False, floatfmt=".3f")}
"""
    p = cfg.path("reports_dir") / "ticket_serving.md"
    p.write_text(text, encoding="utf-8")
    return p
