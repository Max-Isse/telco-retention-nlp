"""reports/themes.md: filter and volumes, cleaning and threading lineage, themes with terms and examples (generated)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from telco_retention.config import Config
from telco_retention.nlp.data import monthly_volumes, volumes
from telco_retention.nlp.themes import examples, save_path


def _md(df: pd.DataFrame, floatfmt: str = ".3f") -> str:
    return str(df.astype(object).to_markdown(index=False, floatfmt=floatfmt)) if len(df) else "_none_"


def theme_names(cfg: Config, k: int) -> dict[int, str]:
    labels = cfg.section("nlp").get("theme_labels") or {}
    return {c: str(labels.get(c, labels.get(str(c), f"cluster {c}"))) for c in range(k)}


def write_themes_report(tweets: pd.DataFrame, steps: list[dict[str, Any]], th: dict[str, Any], cfg: Config) -> Path:
    tables, figs = cfg.path("tables_dir"), cfg.path("figures_dir")
    tables.mkdir(parents=True, exist_ok=True)
    figs.mkdir(parents=True, exist_ok=True)
    names = theme_names(cfg, th["k"])
    tw = tweets.assign(cluster=th["labels"], theme=[names[c] for c in th["labels"]])
    tw[["tweet_id", "brand", "created", "clean", "cluster", "theme"]].to_parquet(save_path(cfg), index=False)
    lineage = pd.DataFrame(steps)
    vol = volumes(tweets)
    themes = (
        tw.groupby(["cluster", "theme"])
        .agg(tweets=("tweet_id", "size"), median_words=("words", "median"))
        .reset_index()
        .assign(share=lambda d: d.tweets / d.tweets.sum())
        .sort_values("tweets", ascending=False)
    )
    themes["top_terms"] = themes.cluster.map(lambda c: ", ".join(th["terms"][c][:8]))
    merged = (
        tw.groupby("theme")
        .agg(tweets=("tweet_id", "size"), clusters=("cluster", lambda s: ", ".join(map(str, sorted(s.unique())))))
        .reset_index()
        .assign(share=lambda d: d.tweets / d.tweets.sum())
        .sort_values("tweets", ascending=False)
    )
    by_brand = pd.crosstab(tw.theme, tw.brand, normalize="columns").round(3).reset_index()
    tables_out = [("nlp_lineage", lineage), ("nlp_volumes", vol), ("themes", merged), ("theme_clusters", themes)]
    for name, df in [*tables_out, ("themes_by_brand", by_brand)]:
        df.to_csv(tables / f"{name}.csv", index=False)
    th["k_table"].to_csv(tables / "themes_k_selection.csv", index=False)
    ex = examples(tw, th["x"], th["labels"], th["centres"], 4)
    ex_text = "\n\n".join(
        f"**{names[c]}** ({int((tw.cluster == c).sum()):,} tweets): " + " · ".join(f"“{e[:140]}”" for e in ex[c])
        for c in themes.cluster
    )
    fig, ax = plt.subplots(figsize=(8, 0.4 * len(merged) + 1))
    ax.barh(merged.theme.iloc[::-1], merged.share.iloc[::-1], color="C0")
    ax.set_xlabel("share of telecom support tweets")
    ax.set_title("Complaint themes (opening customer tweets, US telecoms)")
    fig.tight_layout()
    fig.savefig(figs / "themes_shares.png", dpi=120)
    plt.close(fig)
    months = monthly_volumes(tweets)
    in_window = months[months.tweets >= 100]
    nc = cfg.section("nlp")
    text = f"""<!-- GENERATED by `telco themes` - do not edit by hand. -->
# Telecom support themes (Twitter)

Source: Kaggle `thoughtvector/customer-support-on-twitter` (real public tweets between customers and brands' support
accounts). Not linked to IBM's Telco customers (D-001): themes connect to churn drivers only through service types.

## 1. Filter, threading and cleaning (D-018)

Brands kept: the US phone and internet providers' support accounts ({", ".join(nc["brands"].values())}), matching
IBM's US customer base. Unit: a customer's opening tweet (not a reply to anything) whose first reply came from one of
these brands, paired with that reply. Cleaning removes handles, URLs and emoji, unescapes HTML, collapses whitespace,
drops texts under {nc["min_words"]} words and exact duplicates.

{_md(lineage.assign(rows=lineage.rows.map(lambda v: f"{v:,}")))}

Volumes by brand (reply time = minutes from the customer tweet to the brand's first reply):

{_md(vol, ".1f")}

Time range: almost all tweets fall in {in_window.month.iloc[0]} to {in_window.month.iloc[-1]}
({int(in_window.tweets.sum()):,} of {len(tweets):,}); the few earlier ones are old threads. Months with 100+ tweets:

{_md(in_window)}

## 2. Themes (D-019)

Sentence embeddings (`{nc["embedding_model"]}`), k-means; k chosen by silhouette on a {nc["silhouette_sample"]:,}-tweet
sample:

{_md(th["k_table"])}

k = **{th["k"]}**. Each cluster was labelled by reading its class-based TF-IDF terms, the 12 tweets nearest its centre
and 6 random members (`nlp.theme_labels` in config); phase 6 checks the labels against a hand-labelled sample.

Themes (clusters merged by reading):

{_md(merged)}

![theme shares](figures/themes_shares.png)

Clusters with their class-based TF-IDF terms:

{_md(themes)}

Examples nearest each centre:

{ex_text}

Theme mix by brand (column shares):

{_md(by_brand)}
"""
    path = cfg.path("reports_dir") / "themes.md"
    path.write_text(text, encoding="utf-8")
    return path
