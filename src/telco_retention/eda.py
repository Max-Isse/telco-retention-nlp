"""Decision-focused EDA: who churns, by contract, tenure, services, charges and payment (reports/eda.md, generated).

Every rate is shown with its segment size and a Wilson 95% interval, so small segments are not over-read.
"""

from __future__ import annotations

import itertools
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from telco_retention.config import Config

ADDONS = ["online_security", "online_backup", "device_protection", "tech_support", "streaming_tv", "streaming_movies"]


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return float(centre - half), float(centre + half)


def churn_by(df: pd.DataFrame, col: str) -> pd.DataFrame:
    rows = []
    for level, g in df.groupby(col, observed=True):
        k, n = int(g.churn.sum()), len(g)
        lo, hi = wilson(k, n)
        rows.append(
            {
                col: level,
                "customers": n,
                "share": n / len(df),
                "churners": k,
                "churn_rate": k / n,
                "ci_low": lo,
                "ci_high": hi,
            }
        )
    return pd.DataFrame(rows)


def add_segments(df: pd.DataFrame, cfg: Config) -> pd.DataFrame:
    edges = [int(e) for e in cfg.section("eda")["tenure_bands"]]
    labels = [f"{lo + 1}-{hi}" if lo else f"0-{hi}" for lo, hi in itertools.pairwise(edges)]
    out = df.copy()
    out["tenure_band"] = pd.cut(out.tenure, bins=[-1, *edges[1:]], labels=labels)
    out["addon_services"] = (out[ADDONS] == "Yes").sum(axis=1)
    out["monthly_charges_quintile"] = pd.qcut(
        out.monthly_charges, 5, labels=["Q1 lowest", "Q2", "Q3", "Q4", "Q5 highest"]
    )
    return out


def rules_baseline(df: pd.DataFrame, max_tenure: int = 12) -> dict[str, Any]:
    """Preview of the phase 2 rules baseline: month-to-month contract and tenure <= 12 months."""
    flag = (df.contract == "Month-to-month") & (df.tenure <= max_tenure)
    tp = int((flag & (df.churn == 1)).sum())
    return {
        "rule": f"month-to-month and tenure <= {max_tenure}",
        "flagged": int(flag.sum()),
        "share_flagged": float(flag.mean()),
        "precision": tp / int(flag.sum()),
        "recall": tp / int(df.churn.sum()),
    }


def _md(df: pd.DataFrame, floatfmt: str = ".3f") -> str:
    return str(df.astype(object).to_markdown(index=False, floatfmt=floatfmt))


def write_eda(customers: pd.DataFrame, cfg: Config, layout: str) -> Path:
    df = add_segments(customers, cfg)
    figs, tables = cfg.path("figures_dir"), cfg.path("tables_dir")
    figs.mkdir(parents=True, exist_ok=True)
    tables.mkdir(parents=True, exist_ok=True)
    cuts = [
        "contract",
        "tenure_band",
        "internet_service",
        "addon_services",
        "tech_support",
        "online_security",
        "payment_method",
        "paperless_billing",
        "monthly_charges_quintile",
        "senior_citizen",
    ]
    results = {c: churn_by(df, c) for c in cuts}
    for c, t in results.items():
        t.to_csv(tables / f"eda_churn_by_{c}.csv", index=False)
    cross = (
        df.pivot_table(index="contract", columns="tenure_band", values="churn", aggfunc="mean", observed=True)
        .round(3)
        .reset_index()
    )
    counts = df.pivot_table(index="contract", columns="tenure_band", values="churn", aggfunc="size", observed=True)
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.8))
    for ax, c in zip(axes, ["contract", "tenure_band", "internet_service"], strict=True):
        t = results[c]
        err = [t.churn_rate - t.ci_low, t.ci_high - t.churn_rate]
        ax.bar(t[c].astype(str), t.churn_rate, yerr=err, capsize=3, color="C0")
        ax.axhline(df.churn.mean(), color="0.4", ls="--", lw=1)
        ax.set_title(f"churn rate by {c.replace('_', ' ')}")
        ax.set_ylim(0, 0.7)
        ax.tick_params(axis="x", labelrotation=20, labelsize=8)
    axes[0].set_ylabel("churn rate (95% CI); dashed = base rate")
    fig.tight_layout()
    fig.savefig(figs / "eda_churn_rates.png", dpi=120)
    plt.close(fig)
    base = df.churn.mean()
    rb = rules_baseline(df)
    churn_charges = df.groupby("churn").monthly_charges.median()
    text = f"""<!-- GENERATED by `telco eda` - do not edit by hand. -->
# EDA: who churns, and what that means for targeting

Source layout: **{layout}** ({len(df):,} customers). Base churn rate **{base:.1%}** ({int(df.churn.sum()):,} churners).
Rates carry Wilson 95% intervals and segment sizes. The data has no time dimension (one snapshot per customer).

![churn rates](figures/eda_churn_rates.png)

## Contract

{_md(results["contract"])}

## Tenure (months)

{_md(results["tenure_band"])}

Contract by tenure band (churn rate):

{_md(cross)}

Customers per cell:

{_md(counts.reset_index())}

## Internet service and add-ons

{_md(results["internet_service"])}

Number of add-on services (security, backup, device protection, tech support, streaming TV / movies):

{_md(results["addon_services"])}

Tech support:

{_md(results["tech_support"])}

## Charges

Median monthly charges: churners {churn_charges.get(1, float("nan")):.2f},
stayers {churn_charges.get(0, float("nan")):.2f}.

{_md(results["monthly_charges_quintile"])}

## Payment and billing

{_md(results["payment_method"])}

{_md(results["paperless_billing"])}

## Senior citizens

{_md(results["senior_citizen"])}

## A first targeting rule (the phase 2 rules baseline)

Flag **{rb["rule"]}**: {rb["flagged"]:,} customers ({rb["share_flagged"]:.1%}); precision {rb["precision"]:.1%}
(churners among the flagged, against a base rate of {base:.1%}) and recall {rb["recall"]:.1%} of all churners.
"""
    if "churn_reason" in df.columns:  # extended file: why churners say they left (descriptive only, never a feature)
        reasons = df.loc[df.churn == 1, "churn_reason"].fillna("(missing)").value_counts().rename_axis("churn_reason")
        reason_tbl = reasons.reset_index(name="churners").assign(share=lambda x: x.churners / x.churners.sum())
        reason_tbl.to_csv(tables / "eda_churn_reasons.csv", index=False)
        text += f"""
## Why churners say they left (extended file; outcome-derived, never a model feature)

{_md(reason_tbl.head(12))}

These reasons exist only after a customer has left, so they are excluded from the features (D-003). They show which
themes matter: competitor offers and support attitude, which the support-text analysis (phases 5-6) examines.
"""
    path = cfg.path("reports_dir") / "eda.md"
    path.write_text(text, encoding="utf-8")
    return path
